; manual opcodes demo: fibonacci sequence

GLOBAL main
DEFAULT rel
EXTERN ExitProcess

SECTION .text
main:
    db 0x4D, 0x31, 0xC0 ; XOR r8, r8
    db 0x4D, 0xC7, 0xC1, 0x01, 0x00, 0x00, 0x00 ; MOV r9, 1
.L2:
    db 0x4D, 0x03, 0xC1 ; ADD r8, r9
    db 0x4D, 0x87, 0xC1 ; XCHG r8, r9

    db 0x49, 0x81, 0xF9, 0x40, 0x42, 0x0F, 0x00 ; CMP r9, 1000000 - stop at a million
    db 0x7E, 0xF1 ; JLE .L2 (-15)

    db 0x31, 0xC9 ; XOR ecx, ecx
    CALL ExitProcess